// DMX: the expert layer. Raw channels, held by hand, and the who-wins settings.
// Rows are checked with a channel selected and three channels held by hand.
import type { CommandName } from "../commands.ts";
import { gone, off, works } from "../situations.ts";
import { button, change, choice, control, fader, keep, liveButton, no, remove, toggle, type Control, type Row } from "../spec.ts";

const NO_OUTPUT = off("No working output on this universe");

/** A control that sets or gives back a raw channel, by hand. */
const raw = (row: Omit<Row, "screen" | "kind">): Control =>
  control({
    ...row,
    screen: "DMX",
    kind: "play",
    in: {
      recording: works("Works. Raw channels are not recorded"),
      autopilot: works("Works. A channel held by hand beats the autopilot and the show"),
      empty: works("Works. The channel is not patched: it is set all the same"),
      "output-lost": NO_OUTPUT,
      ...row.in,
    },
  });

const rule = (id: string, name: string, from: string, does: string, states: readonly string[], holding: string): Control =>
  control({
    id: `dmx.who-wins.${id}`,
    name,
    screen: "DMX",
    part: "Who wins",
    from: [from],
    kit: "Picker.segments",
    kind: "setting",
    does,
    sends: ["SetWhoWins"],
    gestures: { ...choice("Sets the rule"), touch: "As a press. 30 px high: an expert screen, not pressed during a show" },
    in: {
      "live-on": works("Works mid-show. Who wins is decided again in the next frame: lights may jump"),
      holding: works(holding),
    },
    first: keep("The one place where who wins is decided"),
    states,
  });

const set = (id: string, name: string, value: string, from: string): Control =>
  raw({
    id: `dmx.channel.${id}`,
    name,
    part: "Channel",
    from: [from],
    kit: "Button.action",
    does: `Holds the selected channel at ${value}, by hand`,
    sends: ["SetChannel"] satisfies CommandName[],
    gestures: liveButton(`Sets the channel to ${value}`),
    in: { holding: works("Works. The channel joins what you hold") },
  });

