const LIVE_IS_ON = off("LIVE is on");
const ON_SCREEN = no("A show file is chosen on screen, with the system's own window");
/** An entry of the show file menu. Checked with the menu open. New and Open swap the whole show: not while LIVE is on. */
const show = (row: Omit<Row, "screen" | "part" | "kind">, swaps: boolean): Control =>
  control({
    learn: ON_SCREEN,
    ...row,
    screen: "Top bar",
    part: "Show file",
    kind: "edit",
    in: { ...(swaps ? { "live-on": LIVE_IS_ON, lock: LIVE_IS_ON, recording: LIVE_IS_ON } : {}), "no-engine": off("Engine not connected"), ...row.in },
  });

const indicator = (
  id: string,
  name: string,
  command: CommandName,
  does: string,
  cells: NonNullable<Parameters<typeof control>[0]["in"]>,
  /** States it shows beyond ready, on and off. */
  more: readonly string[] = [],
): Control =>
  control({
    id: `top.indicator.${id}`,
    name: `${name} indicator`,
    screen: "Top bar",
    part: "LIVE switch",
    from: ["shell/LiveSwitch/button"],
    kit: "Button.toggle",
    kind: "setting",
    does,
    sends: [command],
    gestures: toggle("Turns it off", "it is ready again, or on if LIVE is on"),
    in: {
      "live-off": works("Goes between ready and turned off. Nothing starts before LIVE"),
      "live-on": works("Goes between on and turned off, at once"),
      ...cells,
    },
    feedback: { screen: "The lamp changes when the engine reports it: solid paper and 'On', a mute ring and 'Ready', a dashed ring with the name struck through when off" },
    undo: no("Press it again"),
    machine: "indicator",
    states: ["ready", "on", "off", ...more],
  });

