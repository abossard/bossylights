/** A row of the autopilot's settings. */
const auto = (row: Omit<Row, "screen" | "kind" | "part"> & { part?: string }): Control =>
  control({
    part: "Autopilot, rules",
    ...row,
    screen: "Looks",
    kind: "setting",
    in: { autopilot: works("Works. The autopilot follows it from its next pick on"), ...row.in },
  });

